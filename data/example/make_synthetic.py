"""Generate the SYNTHETIC example workbook (same 27 columns and value domains as the study dataset; random values).
Usage: python data/example/make_synthetic.py [output.xlsx]
"""
import sys, datetime
from pathlib import Path
import numpy as np, pandas as pd

out = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).resolve().parent / "SYNTHETIC_Example_Dataset_176.xlsx"
rng = np.random.default_rng(2026)
rows = []
cats = ["Integration", "API", "Microservice", "Web", "Batch"]; pc = [56, 34, 34, 30, 22]
dbt = ["SQLServer", "MySQL", "PostgreSQL", "Oracle"]; pdb = [46, 34, 22, 16]
for s_i in range(1, 89):
    svc = f"SVC-{s_i:03d}"
    cat = rng.choice(cats, p=np.array(pc) / sum(pc)); crit = rng.choice(["Low", "Medium", "High"], p=[46/176, 86/176, 44/176])
    cx = int(rng.integers(1, 6)); hasdb = int(rng.random() < 0.67); db = rng.choice(dbt, p=np.array(pdb) / sum(pdb)) if hasdb else np.nan
    net = int(rng.random() < 0.68)
    for env in ["Dev", "QA"]:
        fw = int(rng.integers(0, 11)) if net else int(rng.integers(0, 5))
        ext = int(rng.integers(0, 7)); route = int(rng.random() < 0.51); cfgc = int(rng.random() < 0.52)
        owner = rng.choice(["Available", "Delayed", "Unknown"], p=[130/176, 35/176, 11/176]); prev = int(rng.integers(0, 6))
        # execution phase (random, loosely tied to the inputs so that the labels are learnable but not trivial)
        load = 0.35 * cx + 0.6 * hasdb + 0.5 * net + 0.25 * ext + 0.5 * (owner != "Available") + 0.3 * prev + rng.normal(0, 1.0)
        attempts = int(np.clip(1 + round(load / 2), 1, 4)); dbi = int(hasdb and rng.random() < 0.25); neti = int(net and rng.random() < 0.3)
        imgi = int(rng.random() < 0.17)
        vres = "Fail" if load > 4.2 and rng.random() < 0.6 else ("Partial" if load > 2.4 else "Pass")
        dur = int(np.clip(round(9 + 4 * load + rng.normal(0, 3)), 9, 39)); delay = int(np.clip(round(max(0, load - 2) * 1.2 + rng.normal(0, 0.6)), 0, 7)) if vres != "Pass" or rng.random() < 0.15 else 0
        outcome = "Failed" if vres == "Fail" else ("Delayed" if vres == "Partial" or delay > 0 else "Success")
        risk = "High" if (vres == "Fail" or load > 3.6) else ("Low" if (load < 1.6 and vres == "Pass") else "Medium")
        acts = []
        if hasdb: acts.append("Validate db connectivity")
        if net or fw >= 5: acts.append("verify firewall/network rules")
        if owner in ("Delayed", "Unknown"): acts.append("confirm owner availability")
        if cfgc and env == "QA": acts.append("review environment-specific configuration")
        if imgi and env == "QA": acts.append("review image build pipeline")
        if ext >= 3: acts.append("test external integrations")
        if risk == "High": acts.append("schedule extended validation window")
        if not acts: acts.append("standard validation and cutover checklist")
        rows.append(dict(Migration_ID=None, Service_Code=svc, Environment=env, Source_Platform="OCP", Target_Platform="GKE",
                         Service_Category=cat, Business_Criticality=crit, Complexity_Level=cx, Has_DB_Dependency=hasdb, DB_Type=db,
                         Has_Network_Change=net, Firewall_Rules_Count=fw, External_Integrations_Count=ext, Route_Ingress_Changed=route,
                         Has_Config_Change=cfgc, Owner_Availability=owner, Previous_Issues_Count=prev, Validation_Attempts=attempts,
                         DB_Access_Issue=dbi, Network_Access_Issue=neti, Image_Build_Issue=imgi, Validation_Result=vres,
                         Migration_Duration_Hours=dur, Cutover_Delay_Days=delay, Outcome=outcome, Risk_Level=risk,
                         Recommended_Action="; ".join(acts) + "."))
raw = pd.DataFrame(rows); raw["Migration_ID"] = [f"MIG-{i:03d}" for i in range(1, 177)]
assert raw.shape == (176, 27) and raw.Risk_Level.value_counts().min() >= 12, raw.Risk_Level.value_counts()
cleaned = raw.drop(columns=["Migration_ID", "Service_Code", "Source_Platform", "Target_Platform"])
cleaned = cleaned[[c for c in cleaned.columns if c not in ("Outcome", "Risk_Level", "Recommended_Action")] + ["Risk_Level", "Outcome", "Recommended_Action"]]
readme = pd.DataFrame({"SYNTHETIC EXAMPLE DATASET (NOT REAL DATA)": [
    "Purpose", "Generation", "Use", "Columns", "Do not"], "": [
    "A randomly generated workbook with the same 27 columns, 88 services x Dev/QA = 176 rows, and the same value domains as the study dataset, so that the pipeline, the experiments and the application can be run end to end.",
    f"Generated by data/example/make_synthetic.py (numpy seed 2026) on {datetime.date.today().isoformat()}. Values are random draws tied loosely to a latent load variable; they are not derived from, and do not reproduce, any real record.",
    "Results obtained on this file are meaningless as evidence and will not match the figures in the paper or the thesis.",
    "See docs/DATA_DICTIONARY.md for every column, its type, value domain and timing (planning stage vs execution stage).",
    "Do not describe results from this file as findings about real migrations."]})
with pd.ExcelWriter(out, engine="openpyxl") as w:
    readme.to_excel(w, sheet_name="README", index=False)
    raw.to_excel(w, sheet_name="RAW_Dataset_176", index=False)
    cleaned.to_excel(w, sheet_name="CLEANED_Dataset_176", index=False)

print("written", out)
